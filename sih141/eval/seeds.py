"""Where every trial's randomness comes from, written down so it can be checked.

D9 says every published number must be reproducible from a recorded seed and a
committed command. That is only true if the seed itself is reproducible, which
means a trial's seed has to be a **pure function of the trial's identity** --
which experiment, which cell, which index -- and of nothing else. Not of a
counter advanced as work is handed out, not of the worker that picked the trial
up, not of a generator threaded through the sweep. Any of those three would make
a result depend on scheduling, and a result that depends on scheduling cannot be
regenerated by a reviewer with the manifest in front of them.

.. _seed-derivation:

The derivation
--------------
For an experiment name ``e``, a cell name ``c``, a role ``r`` and a
zero-based trial index ``i``:

.. code-block:: text

    material = b"sih141/eval/seed/v1" || 0x00
            || utf8(e)  || 0x00
            || utf8(c)  || 0x00
            || utf8(r)  || 0x00
            || ascii(decimal(i))
    seed     = int.from_bytes(blake2b(material, digest_size=8,
                                      person=b"sih141-eval"), "big")

Three properties, each of which is tested rather than asserted:

* **Pure.** ``trial_seed`` reads no clock, no environment and no global state,
  so worker count, chunk size and completion order cannot reach it.
* **Unambiguous.** ``0x00`` is the separator and :func:`check_name` forbids it
  (and everything else outside ``[a-z0-9._-]``) inside a name, so no two
  distinct identities can build the same ``material``. Without that,
  ``("ab", "c")`` and ``("a", "bc")`` would collide.
* **Independent across roles.** The session's generator and an adversary's
  generator come from different ``r``, so D6 -- every adversary owns its
  randomness and never reads the session's -- is a property of the derivation
  rather than a convention the caller has to remember. The test uses
  :func:`sih141.attacks.isolation.same_stream`, which compares realised draws,
  not seeds.

Why BLAKE2b rather than, say, ``hash((e, c, r, i))``: Python's ``hash`` is
randomised per process by PYTHONHASHSEED, which is precisely the "depends on
which process ran it" failure this module exists to rule out. Why a
``person=`` parameter: it domain-separates this project's seeds from any other
BLAKE2b use, so the byte string above is the whole specification.

Examples
--------
The derivation is fixed, so these are the actual seeds the ``honest`` experiment
runs under. If a change to this module moves them, this doctest fails, and it
should: every number already published was produced under the old ones.

>>> from sih141.eval.seeds import trial_seed, trial_seeds
>>> trial_seed("honest", "l192", 0)
15537000204045215064
>>> trial_seed("honest", "l192", 1)
10336262205737360728
>>> trial_seed("honest", "l192", 0, role="adversary")
4703901814294326032

The pair a trial actually receives:

>>> pair = trial_seeds("honest", "l192", 0)
>>> pair.session == trial_seed("honest", "l192", 0)
True
>>> pair.adversary == trial_seed("honest", "l192", 0, role="adversary")
True
>>> pair.session == pair.adversary
False
"""

from __future__ import annotations

import hashlib
import re
from dataclasses import dataclass
from typing import Any, Final

import numpy as np

from sih141.core.rng import seed_to_generator

__all__ = [
    "ADVERSARY_ROLE",
    "NAME_PATTERN",
    "SEED_DOMAIN",
    "SEED_PERSON",
    "SESSION_ROLE",
    "TrialSeeds",
    "check_name",
    "trial_seed",
    "trial_seeds",
]

SEED_DOMAIN: Final[bytes] = b"sih141/eval/seed/v1"
"""bytes: Domain separator, versioned. Bumping it re-seeds every experiment."""

SEED_PERSON: Final[bytes] = b"sih141-eval"
"""bytes: BLAKE2b personalisation, at most 16 bytes."""

SESSION_ROLE: Final[str] = "session"
"""str: The role whose generator drives the protocol run itself."""

ADVERSARY_ROLE: Final[str] = "adversary"
"""str: The role whose generator drives the attack, and only the attack (D6)."""

NAME_PATTERN: Final[re.Pattern[str]] = re.compile(r"\A[a-z0-9][a-z0-9._-]{0,63}\Z")
"""re.Pattern: Legal experiment, cell and role names.

Deliberately narrow, and it is doing two jobs at once. It keeps ``0x00`` --
and every other byte that could make two identities hash alike -- out of the
seed material, and it keeps path separators, drive letters, spaces and
upper-case out of names that become directory components on a case-insensitive
filesystem.
"""


def check_name(value: Any, *, what: str = "name") -> str:
    """Return ``value`` if it is a legal identity component, else raise.

    Parameters
    ----------
    value : object
        The candidate experiment, cell or role name.
    what : str, optional
        Keyword-only. What to call it in the error message.

    Returns
    -------
    str
        ``value`` unchanged.

    Raises
    ------
    TypeError
        If ``value`` is not a string.
    ValueError
        If it does not match :data:`NAME_PATTERN`.

    Examples
    --------
    >>> from sih141.eval.seeds import check_name
    >>> check_name("qber-sweep")
    'qber-sweep'
    >>> check_name("Two Words")
    Traceback (most recent call last):
        ...
    ValueError: name 'Two Words' is not a legal identity component...
    """
    if not isinstance(value, str):
        raise TypeError(f"{what} must be a str, got {type(value).__name__}")
    if NAME_PATTERN.match(value) is None:
        raise ValueError(
            f"{what} {value!r} is not a legal identity component: it must "
            f"match {NAME_PATTERN.pattern}. Names are separated by a NUL byte "
            f"inside the seed material and are used verbatim as directory "
            f"components, so anything looser makes two trials collide or "
            f"escape the results directory."
        )
    return value


def trial_seed(
    experiment: str, cell: str, index: int, *, role: str = SESSION_ROLE
) -> int:
    """Derive one trial's 64-bit seed from its identity alone.

    Parameters
    ----------
    experiment : str
        Experiment name, matching :data:`NAME_PATTERN`.
    cell : str
        Cell name within the experiment, matching :data:`NAME_PATTERN`.
    index : int
        Zero-based trial index within the cell.
    role : str, optional
        Keyword-only. Which stream this seed drives; :data:`SESSION_ROLE` or
        :data:`ADVERSARY_ROLE`, or any other legal name for a third stream.

    Returns
    -------
    int
        A seed in ``[0, 2**64)``, suitable for
        :func:`~sih141.core.rng.seed_to_generator`.

    Raises
    ------
    TypeError
        If a name is not a string, or ``index`` is not an integer.
    ValueError
        If a name is illegal, or ``index`` is negative.

    Notes
    -----
    The derivation is spelled out byte for byte in the module docstring, under
    :ref:`seed-derivation`. It reads nothing but its four arguments, which is
    what makes a parallel sweep reproducible: the seed a trial runs under is
    the same whether it was the first trial handed to worker 0 or the last one
    handed to worker 19.

    Examples
    --------
    >>> from sih141.eval.seeds import trial_seed
    >>> seed = trial_seed("demo", "cell-a", 3)
    >>> 0 <= seed < 2 ** 64
    True

    Identity is the whole input, so every component moves the seed:

    >>> len({
    ...     trial_seed("demo", "cell-a", 3),
    ...     trial_seed("demo", "cell-b", 3),
    ...     trial_seed("other", "cell-a", 3),
    ...     trial_seed("demo", "cell-a", 4),
    ...     trial_seed("demo", "cell-a", 3, role="adversary"),
    ... })
    5

    And the separator does its job -- these two identities would collide under
    plain concatenation:

    >>> trial_seed("ab", "c", 0) == trial_seed("a", "bc", 0)
    False
    """
    check_name(experiment, what="experiment")
    check_name(cell, what="cell")
    check_name(role, what="role")
    if isinstance(index, bool) or not isinstance(index, int):
        raise TypeError(f"index must be an int, got {type(index).__name__}")
    if index < 0:
        raise ValueError(f"index must be non-negative, got {index}")
    material = b"\x00".join(
        (
            SEED_DOMAIN,
            experiment.encode("utf-8"),
            cell.encode("utf-8"),
            role.encode("utf-8"),
            str(index).encode("ascii"),
        )
    )
    digest = hashlib.blake2b(material, digest_size=8, person=SEED_PERSON).digest()
    return int.from_bytes(digest, "big")


@dataclass(frozen=True)
class TrialSeeds:
    """The two seeds one trial runs under, kept apart on purpose.

    D6 requires that an adversary own its randomness and never read the
    session's. Handing out two seeds derived under different roles makes that
    structural: there is no generator both sides could share even by accident,
    because neither is ever passed the other's.

    Attributes
    ----------
    experiment : str
        Experiment name.
    cell : str
        Cell name.
    index : int
        Trial index within the cell.
    session : int
        Seed for :class:`~sih141.protocol.session.QDSSession`.
    adversary : int
        Seed for the attack, if the cell mounts one.

    Examples
    --------
    >>> from sih141.eval.seeds import TrialSeeds, trial_seeds
    >>> pair = trial_seeds("demo", "cell-a", 0)
    >>> pair.experiment, pair.cell, pair.index
    ('demo', 'cell-a', 0)
    >>> sorted(pair.to_dict())
    ['adversary', 'cell', 'experiment', 'index', 'session']

    The generators come out already resolved, through the one sanctioned
    scalar-to-generator boundary (D3):

    >>> import numpy as np
    >>> generator = pair.session_rng()
    >>> isinstance(generator, np.random.Generator)
    True
    >>> pair.session_rng() is generator
    False
    """

    experiment: str
    cell: str
    index: int
    session: int
    adversary: int

    def session_rng(self) -> np.random.Generator:
        """Return a fresh generator seeded from :attr:`session`.

        Returns
        -------
        numpy.random.Generator
            A new generator every call, so two calls give two identical
            streams rather than one advanced one.
        """
        return seed_to_generator(self.session)

    def adversary_rng(self) -> np.random.Generator:
        """Return a fresh generator seeded from :attr:`adversary`.

        Returns
        -------
        numpy.random.Generator
            A new generator every call.
        """
        return seed_to_generator(self.adversary)

    def to_dict(self) -> dict[str, Any]:
        """Return a JSON-serialisable view.

        Returns
        -------
        dict
            The identity and both seeds, so a reviewer reading one trial's
            record can re-derive it without the harness.
        """
        return {
            "experiment": self.experiment,
            "cell": self.cell,
            "index": self.index,
            "session": self.session,
            "adversary": self.adversary,
        }


def trial_seeds(experiment: str, cell: str, index: int) -> TrialSeeds:
    """Derive the whole seed set for one trial.

    Parameters
    ----------
    experiment : str
        Experiment name.
    cell : str
        Cell name.
    index : int
        Zero-based trial index.

    Returns
    -------
    TrialSeeds

    Examples
    --------
    >>> from sih141.eval.seeds import trial_seeds
    >>> trial_seeds("honest", "l192", 0).session
    15537000204045215064
    """
    return TrialSeeds(
        experiment=experiment,
        cell=cell,
        index=index,
        session=trial_seed(experiment, cell, index, role=SESSION_ROLE),
        adversary=trial_seed(experiment, cell, index, role=ADVERSARY_ROLE),
    )
